	/** The standard header of a Java file. */
	public static String header(final String pkg, final String className) {
		String notice = gama.ui.devtools.util.JavaHeaderText.header(className + ".java", null,
				gama.ui.devtools.preferences.JavaHeaderSettings.version(),
				gama.ui.devtools.preferences.JavaHeaderSettings.year(), "\n");
		return notice + "package " + pkg + ";\n\n";
	}

	/** Turns a GAML name (that may contain characters invalid in Java) into a Java identifier. */
	public static String javaIdentifier(final String name) {
		StringBuilder sb = new StringBuilder();
		for (char c : name.toCharArray()) { sb.append(Character.isJavaIdentifierPart(c) ? c : '_'); }
		if (sb.isEmpty() || !Character.isJavaIdentifierStart(sb.charAt(0))) { sb.insert(0, '_'); }
		return javax.lang.model.SourceVersion.isKeyword(sb) ? "_" + sb : sb.toString();
	}

	/** Turns a name into a valid GAML model identifier. */
	public static String gamlIdentifier(final String name) {
		StringBuilder sb = new StringBuilder();
		for (char c : name.toCharArray()) { if (Character.isLetterOrDigit(c) || c == '_') { sb.append(c); } }
		if (sb.isEmpty() || Character.isDigit(sb.charAt(0))) { sb.insert(0, "model_"); }
		return sb.toString();
	}

	/** A suggested GAML name for a class name ({@code MyFancySkill -> my_fancy}). */
	public static String gamlNameFor(final String className, final String suffixToRemove) {
		String base = className;
		if (suffixToRemove != null && base.endsWith(suffixToRemove) && base.length() > suffixToRemove.length()) {
			base = base.substring(0, base.length() - suffixToRemove.length());
		}
		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < base.length(); i++) {
			char c = base.charAt(i);
			if (Character.isUpperCase(c) && i > 0) { sb.append('_'); }
			sb.append(Character.toLowerCase(c));
		}
		return sb.toString();
	}

	private static String list(final String key, final List<String> values) {
		String prefix = key + " = ";
		String indent = " ".repeat(prefix.length());
		StringBuilder sb = new StringBuilder();
		for (int i = 0; i < values.size(); i++) {
			sb.append(i == 0 ? prefix : indent).append(values.get(i)).append(i < values.size() - 1 ? ",\\\n" : "\n");
		}
		return sb.toString();
	}

	private static String xml(final String s) {
		return s == null ? "" : s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"",
				"&quot;");
	}

