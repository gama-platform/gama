	/**
	 * A skill with one attribute (getter/setter) and one action.
	 *
	 * @param skillName
	 *            the GAML name of the skill
	 */
	public static String skill(final String pkg, final String className, final String skillName) {
		return header(pkg, className) + """
				import gama.annotations.action;
				import gama.annotations.arg;
				import gama.annotations.doc;
				import gama.annotations.getter;
				import gama.annotations.setter;
				import gama.annotations.skill;
				import gama.annotations.variable;
				import gama.annotations.vars;
				import gama.annotations.support.IConcept;
				import gama.api.gaml.types.IType;
				import gama.api.kernel.agent.IAgent;
				import gama.api.kernel.skill.Skill;
				import gama.api.runtime.scope.IScope;

				/**
				 * The skill '%2$s'. Agents of species declaring {@code skills: [%2$s]} get its attributes and actions.
				 */
				@skill (
						name = %1$s.SKILL_NAME,
						concept = { IConcept.SKILL })
				@vars ({ @variable (
						name = %1$s.COUNTER,
						type = IType.INT,
						init = "0",
						doc = @doc ("The number of times the agent has greeted someone")) })
				@doc ("Describe here what the '%2$s' skill provides to the agents that use it")
				public class %1$s extends Skill {

					/** The GAML name of the skill. */
					public static final String SKILL_NAME = "%2$s";

					/** The name of the attribute provided by the skill. */
					public static final String COUNTER = "greetings_count";

					/** Returns the value of the attribute for this agent. */
					@getter (COUNTER)
					public Integer getCounter(final IAgent agent) {
						Object value = agent.getAttribute(COUNTER);
						return value instanceof Integer i ? i : 0;
					}

					/** Changes the value of the attribute for this agent. */
					@setter (COUNTER)
					public void setCounter(final IAgent agent, final Integer value) {
						agent.setAttribute(COUNTER, value);
					}

					/** An action available to the agents: {@code do greet to: "someone";} */
					@action (
							name = "greet",
							args = { @arg (
									name = "to",
									type = IType.STRING,
									optional = true,
									doc = @doc ("The name of the person to greet (default: 'world')")) },
							doc = @doc (
									value = "Greets someone and increments the number of greetings",
									returns = "the greeting message"))
					public String greet(final IScope scope) {
						IAgent agent = scope.getAgent();
						String to = scope.hasArg("to") ? (String) scope.getArg("to", IType.STRING) : "world";
						setCounter(agent, getCounter(agent) + 1);
						return "Hello " + to + " from " + agent.getName();
					}

				}
				""".formatted(className, skillName);
	}

