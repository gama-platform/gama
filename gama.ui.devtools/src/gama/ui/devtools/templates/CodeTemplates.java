	/** {@code META-INF/MANIFEST.MF}. {@code libJars} are project-relative paths of the jars in {@code libs/}. */
	public static String manifest(final PluginSpec spec, final List<String> libJars) {
		StringBuilder sb = new StringBuilder();
		sb.append("Manifest-Version: 1.0\n");
		sb.append("Bundle-ManifestVersion: 2\n");
		sb.append("Bundle-Name: ").append(spec.name()).append("\n");
		sb.append("Bundle-SymbolicName: ").append(spec.id()).append(";singleton:=true\n");
		sb.append("Bundle-Version: 0.0.0.qualifier\n");
		sb.append("Bundle-Vendor: ").append(spec.vendor()).append("\n");
		sb.append("Require-Bundle: gama.core,\n gama.dependencies\n");
		sb.append("Bundle-ActivationPolicy: lazy\n");
		sb.append("Bundle-RequiredExecutionEnvironment: ").append(JAVA_EE).append("\n");
		sb.append("Automatic-Module-Name: ").append(spec.id()).append("\n");
		sb.append("Bundle-ClassPath: .");
		for (String jar : libJars) { sb.append(",\n ").append(jar); }
		sb.append("\n");
		return sb.toString();
	}

	/** {@code build.properties}. */
	public static String buildProperties(final PluginSpec spec, final List<String> libJars) {
		List<String> bin = new ArrayList<>(List.of(".", "plugin.xml", "META-INF/"));
		if (spec.hasModels()) { bin.add("models/"); }
		bin.addAll(libJars);
		StringBuilder sb = new StringBuilder();
		sb.append("source.. = src/,\\\n           gaml/\n");
		sb.append("output.. = bin/\n");
		sb.append("jre.compilation.profile = ").append(JAVA_EE).append("\n");
		sb.append(list("bin.includes", bin));
		sb.append("javacDefaultEncoding.. = UTF-8\n");
		return sb.toString();
	}

