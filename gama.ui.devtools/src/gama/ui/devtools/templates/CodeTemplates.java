	/** {@code .classpath}, with the libraries first, then {@code src} and the generated {@code gaml} folder. */
	public static String classpath(final List<String> libJars) {
		StringBuilder sb = new StringBuilder("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<classpath>\n");
		for (String jar : libJars) {
			sb.append("\t<classpathentry exported=\"true\" kind=\"lib\" path=\"").append(jar).append("\"/>\n");
		}
		sb.append("\t<classpathentry kind=\"con\" path=\"org.eclipse.jdt.launching.JRE_CONTAINER/"
				+ "org.eclipse.jdt.internal.debug.ui.launcher.StandardVMType/" + JAVA_EE + "\"/>\n");
		sb.append("\t<classpathentry kind=\"con\" path=\"org.eclipse.pde.core.requiredPlugins\"/>\n");
		sb.append("\t<classpathentry kind=\"src\" path=\"src\"/>\n");
		sb.append("""
					<classpathentry kind="src" path="gaml">
						<attributes>
							<attribute name="optional" value="true"/>
						</attributes>
					</classpathentry>
					<classpathentry kind="output" path="bin"/>
				</classpath>
				""");
		return sb.toString();
	}

